import 'server-only';
import { jsPDF } from 'jspdf';
import autoTable, { type CellHookData, type RowInput } from 'jspdf-autotable';
import { COMPANY } from '@/lib/company';
import { formatDate, formatDateTime } from '@/lib/dates';
import { formatNumber } from '@/lib/format';
import { STATUS_LABEL, type ChequeStatus } from '@/types';
import { LOGO_ASPECT, LOGO_PNG_BASE64 } from './logoData';
import { columnLabel } from './columns';
import type { Cell, Column, ReportData } from './types';

type RGB = [number, number, number];

// Letterhead palette
const GREEN: RGB = [22, 138, 67];
const GREEN_SOFT: RGB = [230, 245, 235];
const GREEN_MID: RGB = [205, 234, 214];
const INK: RGB = [19, 43, 63];
const MUTED: RGB = [83, 102, 122];
const BLACK: RGB = [0, 0, 0];
const LINE: RGB = [221, 232, 225];
const STATUS_COLOR: Partial<Record<ChequeStatus, RGB>> = {
  IN_HAND: [164, 90, 6],
  PENDING: [164, 90, 6],
  DEPOSITED: [11, 111, 179],
  CREDITED: [21, 128, 61],
  CLEARED: [21, 128, 61],
  RETURNED: [190, 18, 60],
  CANCELLED: [83, 102, 122],
};

// The built-in PDF fonts only cover Latin-1; replace anything else so text never renders as garbage.
export function pdfText(value: string | null | undefined): string {
  if (!value) return '';
  return value
    .replace(/[–—−]/g, '-')
    .replace(/[‘’]/g, "'")
    .replace(/[“”]/g, '"')
    .replace(/…/g, '...')
    .replace(/[^\x00-\xFF]/g, '?');
}

function formatCell(value: Cell, col: Column): string {
  if (value === null || value === undefined || value === '') return col.type === 'money' || col.type === 'number' ? '' : '-';
  switch (col.type) {
    case 'money':
      return typeof value === 'number' ? formatNumber(value) : pdfText(String(value));
    case 'number':
      return typeof value === 'number' ? value.toLocaleString() : pdfText(String(value));
    case 'date':
      return /^\d{4}-\d{2}-\d{2}$/.test(String(value)) ? formatDate(String(value)) : pdfText(String(value));
    case 'status':
      return STATUS_LABEL[value as ChequeStatus] ?? String(value);
    default:
      return pdfText(String(value));
  }
}

export function renderPdf(report: ReportData, username: string): Uint8Array {
  const widest = Math.max(...report.sections.map((s) => s.columns.length), 1);
  const doc = new jsPDF({ orientation: widest > 5 ? 'landscape' : 'portrait', unit: 'mm', format: 'a4' });
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 14;
  const right = pageWidth - margin;
  const generated = new Date();

  // ── Letterhead ─────────────────────────────────────────────────────────────
  doc.setFillColor(...GREEN);
  doc.rect(0, 0, pageWidth, 2.5, 'F');
  const logoH = 16;
  doc.addImage(LOGO_PNG_BASE64, 'PNG', margin, 6, logoH * LOGO_ASPECT, logoH);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  doc.setTextColor(...INK);
  doc.text(COMPANY.legalName, right, 10, { align: 'right' });
  doc.text(COMPANY.address, right, 14.5, { align: 'right' });
  doc.text(`${COMPANY.phone}  |  ${COMPANY.email}`, right, 19, { align: 'right' });
  doc.setDrawColor(...GREEN);
  doc.setLineWidth(0.5);
  doc.line(margin, 25, right, 25);

  // ── Title block: report title, parameters, generated date/time and user ───
  doc.setTextColor(...BLACK);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(13);
  doc.text(pdfText(report.title), margin, 32);
  doc.setTextColor(...INK);
  doc.setFontSize(9.5);
  doc.text(pdfText(report.subtitle), margin, 37.5, { maxWidth: pageWidth * 0.6 });
  doc.setTextColor(...MUTED);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  doc.text(`Generated: ${formatDateTime(generated)}`, right, 32, { align: 'right' });
  doc.text(`Generated by: ${pdfText(username)}`, right, 37.5, { align: 'right' });

  // ── Summary boxes ──────────────────────────────────────────────────────────
  let y = 43;
  if (report.summary.length) {
    const gap = 3;
    const perRow = Math.min(report.summary.length, 4);
    const boxW = (right - margin - gap * (perRow - 1)) / perRow;
    report.summary.forEach((s, i) => {
      const col = i % perRow;
      const row = Math.floor(i / perRow);
      const x = margin + col * (boxW + gap);
      const by = y + row * 16;
      doc.setDrawColor(...LINE);
      doc.setLineWidth(0.2);
      doc.setFillColor(248, 251, 249);
      doc.roundedRect(x, by, boxW, 13, 1.5, 1.5, 'FD');
      doc.setTextColor(...MUTED);
      doc.setFont('helvetica', 'normal');
      doc.setFontSize(7);
      doc.text(pdfText(s.label).toUpperCase(), x + 3, by + 4.8);
      doc.setTextColor(...INK);
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(10);
      doc.text(pdfText(s.value), x + 3, by + 10.2);
    });
    y += Math.ceil(report.summary.length / perRow) * 16 + 2;
  }

  // ── Sections ───────────────────────────────────────────────────────────────
  if (report.sections.every((s) => s.rows.length === 0 || s.rows.every((r) => r.kind === 'total'))) {
    doc.setTextColor(...MUTED);
    doc.setFontSize(10);
    doc.text('No records match the selected options.', margin, y + 6);
  }

  const lastY = () => (doc as unknown as { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY ?? y;

  report.sections.forEach((section, index) => {
    if (section.rows.length === 0) return;
    let startY = index === 0 ? y : lastY() + 7;
    if (section.title) {
      if (startY > pageHeight - 30) {
        doc.addPage();
        startY = 16;
      }
      doc.setTextColor(...BLACK);
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(10);
      doc.text(pdfText(section.title), margin, startY + 1);
      startY += 3;
    }

    const alignOf = (c: Column) => (c.type === 'money' || c.type === 'number' ? 'right' : c.type === 'status' ? 'center' : 'left');
    const body: RowInput[] = section.rows.map((r) =>
      section.columns.map((c) => ({
        // Blank (not "-") in the empty cells of subtotal/total rows.
        content: r.kind && r.kind !== 'data' && (r.cells[c.key] ?? null) === null ? '' : formatCell(r.cells[c.key] ?? null, c),
        styles: {
          halign: alignOf(c),
          fontStyle: r.kind && r.kind !== 'data' ? 'bold' : c.type === 'money' ? 'bold' : 'normal',
          fillColor: r.kind === 'total' ? GREEN_MID : r.kind === 'subtotal' ? GREEN_SOFT : undefined,
        },
      }))
    );

    autoTable(doc, {
      startY,
      theme: 'grid',
      margin: { left: margin, right: margin, bottom: 14, top: 14 },
      head: [section.columns.map((c) => ({ content: pdfText(columnLabel(c)), styles: { halign: alignOf(c) } }))],
      body,
      headStyles: { fillColor: GREEN, textColor: [255, 255, 255], fontSize: 7.5, fontStyle: 'bold' },
      bodyStyles: { textColor: INK, fontSize: 7.5, lineColor: LINE, cellPadding: 1.8 },
      alternateRowStyles: { fillColor: [250, 252, 251] },
      showHead: 'everyPage',
      didParseCell: (data: CellHookData) => {
        const col = section.columns[data.column.index];
        if (data.section === 'body' && col?.type === 'status') {
          const color = STATUS_COLOR[section.rows[data.row.index]?.cells[col.key] as ChequeStatus];
          if (color) {
            data.cell.styles.textColor = color;
            data.cell.styles.fontStyle = 'bold';
          }
        }
      },
    });
  });

  // ── Footer ─────────────────────────────────────────────────────────────────
  const pageCount = doc.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7);
    doc.setTextColor(...MUTED);
    doc.text(
      `${COMPANY.legalName}  |  ${pdfText(report.title)}  |  Generated ${formatDateTime(generated)} by ${pdfText(username)}  |  Page ${i} of ${pageCount}`,
      pageWidth / 2,
      pageHeight - 6,
      { align: 'center' }
    );
  }

  return new Uint8Array(doc.output('arraybuffer'));
}
